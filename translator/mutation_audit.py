#!/usr/bin/env python3
"""mutation_audit — prove each spike can FAIL (oracle liveness by mutation).

A spike that cannot fail proves nothing: a vacuous compare (0 == 0), inputs
that are never fuzzed, or an output slot the body never writes all yield a
green run whatever the C does. This tool takes each spike generated by
strict_audit.py (parity/src/spike_<name>_strict.c), injects small textual
mutations into the inlined C body only (operator swaps, constant +1), rebuilds
each mutant and runs it. A mutant is KILLED when the spike reports a failure
(contract mode, plus strict mode if --strict). A routine whose mutants all
survive has a spike that is blind to its own body.

Some survivors are equivalent mutants (e.g. a mutated cycle-charge constant
in snes_runCycles(), which no WRAM/register compare can see) — the report
prints each survivor's line so a human can tell. Lines containing
snes_runCycles are never mutated for that reason.

Usage:
    python translator/mutation_audit.py [--only D038407,...] [--mutants 6]
                                        [--trials 500] [--strict] [--jobs 8]
Prereq: run strict_audit.py first (it leaves parity/src/spike_*_strict.c).
Output: translator/runs/mutation_audit/{mutation_audit.jsonl,MUTATION_AUDIT.md}
"""
from __future__ import annotations

import argparse
import concurrent.futures as cf
import json
import os
import random
import re
import shlex
import subprocess
import sys
import tempfile
from collections import Counter
from datetime import date
from pathlib import Path

HERE = Path(__file__).resolve().parent
PORT_ROOT = HERE.parent
PARITY = PORT_ROOT / "parity"
ROM = PORT_ROOT / "upstream" / "rom" / "ff4-jp1.sfc"
AUDIT = HERE / "runs" / "strict_audit" / "strict_audit.jsonl"

BODY_START = "// LLM-translated C function"
BODY_END = "// Common helpers"
# (pattern, replacement) — applied to ONE occurrence per mutant.
OPERATORS = [
    (r"(?<![+\-=<>!&|])\+(?![+=])", "-"),
    (r"(?<![\-=<>!&|>])-(?![\->=])", "+"),
    (r"==", "!="),
    (r"!=", "=="),
    (r"(?<![<>=])<(?![<=])", "<="),
    (r"(?<![<>=-])>(?![>=])", ">="),
    (r"(?<![&])&(?![&=])", "|"),
    (r"(?<![|])\|(?![|=])", "&"),
    (r"\b0x([0-9A-Fa-f]+)\b", None),   # hex constant + 1
]
_SKIP_LINE = re.compile(r"snes_runCycles|^\s*(#|//|/\*|\*)|printf")
_SUMMARY_RE = re.compile(r"=== summary === trials:\s*(\d+),\s*fails:\s*(\d+)")
_STRICT_RE = re.compile(r"=== strict === trials:\s*(\d+),\s*strict_fails:\s*(\d+)")


def make_vars() -> dict:
    """CC/CFLAGS/CORE_SRC/LDFLAGS as make expands them (no rule changes).
    A second -f file instead of --eval: macOS ships GNU make 3.81."""
    out = {}
    with tempfile.NamedTemporaryFile("w", suffix=".mk", delete=False) as fh:
        fh.write("print-%:\n\t@echo $($*)\n")
        extra = fh.name
    try:
        for var in ("CC", "CFLAGS", "CORE_SRC", "LDFLAGS"):
            r = subprocess.run(["make", "-s", "-C", str(PARITY), "-f", "Makefile", "-f", extra,
                                f"print-{var}"], capture_output=True, text=True)
            out[var] = r.stdout.strip()
    finally:
        os.unlink(extra)
    if not out["CC"] or not out["CORE_SRC"]:
        sys.exit(f"error: could not read parity/Makefile variables: {out}")
    return out


def sites(src: str) -> list[tuple[int, int, int, str]]:
    """(op_index, abs_start, abs_end, replacement) over the inlined body."""
    a, b = src.find(BODY_START), src.find(BODY_END)
    if a < 0 or b < 0:
        return []
    found = []
    pos = a
    for line in src[a:b].splitlines(keepends=True):
        code = line.split("//", 1)[0]
        if not _SKIP_LINE.search(line):
            for k, (pat, rep) in enumerate(OPERATORS):
                for m in re.finditer(pat, code):
                    if rep is None:
                        val = int(m.group(1), 16)
                        r = f"0x{val + 1:X}"
                    else:
                        r = rep
                    found.append((k, pos + m.start(), pos + m.end(), r))
        pos += len(line)
    return found


def mutate_and_run(spike: Path, site, idx: int, mk: dict, trials: int, strict: bool, workdir: Path,
                   extra_src: str) -> dict:
    src = spike.read_text()
    _, s, e, rep = site
    mutant = src[:s] + rep + src[e:]
    line_no = src.count("\n", 0, s) + 1
    line = src.splitlines()[line_no - 1].strip()
    msrc = workdir / f"{spike.stem}_m{idx}.c"
    mbin = workdir / f"{spike.stem}_m{idx}"
    msrc.write_text(mutant)
    cmd = (f"{mk['CC']} {mk['CFLAGS']} -o {shlex.quote(str(mbin))} {shlex.quote(str(msrc))} "
           f"{mk['CORE_SRC']} {extra_src} {mk['LDFLAGS']}")
    b = subprocess.run(cmd, shell=True, cwd=str(PARITY), capture_output=True, text=True)
    res = {"line": line_no, "orig": src[s:e], "rep": rep, "code": line[:120]}
    if b.returncode != 0:
        return {**res, "outcome": "no_compile"}
    env = dict(os.environ)
    if strict:
        env["FF4_SPIKE_STRICT"] = "gate"
    try:
        r = subprocess.run([str(mbin), str(ROM), str(trials)], capture_output=True, text=True,
                           timeout=60, env=env)
    except subprocess.TimeoutExpired:
        return {**res, "outcome": "killed_timeout"}
    finally:
        for p in (msrc, mbin):
            p.unlink(missing_ok=True)
    m = _SUMMARY_RE.search(r.stdout)
    if not m:
        return {**res, "outcome": "killed_crash"}
    st = _STRICT_RE.search(r.stdout)
    killed = int(m.group(2)) > 0 or (strict and st and int(st.group(2)) > 0)
    return {**res, "outcome": "killed" if killed else "SURVIVED"}


def extra_sources(rec: dict) -> str:
    """SPIKE_EXTRA_SRC of the routine's source (paths are relative to parity/)."""
    src = PORT_ROOT.parent / rec.get("source", "")
    if not src.is_file():
        return ""
    m = re.search(r"//\s*SPIKE_EXTRA_SRC:\s*([^\n]+)", src.read_text(), re.IGNORECASE)
    return " ".join(p.strip() for p in m.group(1).split(",")) if m else ""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", default="")
    ap.add_argument("--mutants", type=int, default=6)
    ap.add_argument("--trials", type=int, default=500)
    ap.add_argument("--strict", action="store_true", help="a strict-mode divergence also kills")
    ap.add_argument("--jobs", type=int, default=os.cpu_count() or 4)
    ap.add_argument("--seed", type=int, default=20261010)
    ap.add_argument("--out", type=Path, default=HERE / "runs" / "mutation_audit")
    ap.add_argument("--audit", type=Path, default=AUDIT, help="strict_audit.jsonl to read")
    args = ap.parse_args(argv)

    audit = [json.loads(l) for l in args.audit.read_text().splitlines() if l.strip()]
    only = set(filter(None, args.only.split(",")))
    recs = [r for r in audit if r.get("status") == "ran" and r.get("contract_fails") == 0
            and (not only or r["id"] in only)]
    mk = make_vars()
    rng = random.Random(args.seed)
    results = []
    with tempfile.TemporaryDirectory(prefix="ff4mut-") as td, \
            cf.ThreadPoolExecutor(max_workers=args.jobs) as ex:
        work = []
        for r in recs:
            slug = r["target"].removeprefix("ff4-spike-strict-")
            spike = PARITY / "src" / f"spike_{slug}_strict.c"
            if not spike.is_file():
                results.append({**r, "mut_status": "no_spike_source"})
                continue
            ss = sites(spike.read_text())
            if not ss:
                results.append({**r, "mut_status": "no_sites"})
                continue
            pick = rng.sample(ss, min(args.mutants, len(ss)))
            extra = extra_sources(r)
            futs = [ex.submit(mutate_and_run, spike, s, i, mk, args.trials, args.strict, Path(td), extra)
                    for i, s in enumerate(pick)]
            work.append((r, futs, len(ss)))
        for r, futs, nsites in work:
            muts = [f.result() for f in futs]
            c = Counter(m["outcome"] for m in muts)
            scored = [m for m in muts if m["outcome"] != "no_compile"]
            killed = sum(1 for m in scored if m["outcome"].startswith("killed"))
            rec = {"id": r["id"], "name": r["name"], "level": r["level"], "sites": nsites,
                   "mutants": len(muts), "scored": len(scored), "killed": killed,
                   "outcomes": dict(c), "survivors": [m for m in muts if m["outcome"] == "SURVIVED"],
                   "mut_status": "ran"}
            results.append(rec)
            print(f"[mut] {r['id']} {r['name']}: killed {killed}/{len(scored)}", file=sys.stderr)

    args.out.mkdir(parents=True, exist_ok=True)
    with (args.out / "mutation_audit.jsonl").open("w") as fh:
        for r in sorted(results, key=lambda r: r["id"]):
            fh.write(json.dumps(r) + "\n")
    ran = [r for r in results if r.get("mut_status") == "ran" and r["scored"]]
    blind = [r for r in ran if r["killed"] == 0]
    weak = [r for r in ran if 0 < r["killed"] < r["scored"]]
    lines = [
        "# Spike liveness (mutation) audit", "",
        f"Generated by `translator/mutation_audit.py` on {date.today().isoformat()} — up to "
        f"{args.mutants} operator/constant mutants per routine injected into the inlined C body, "
        f"{args.trials} trials each, kill = contract failure"
        + (" or strict divergence" if args.strict else "") + ". A **blind** spike killed none of "
        "its mutants: it cannot detect a broken body. Survivors may be equivalent mutants — "
        "read the line before concluding.", "",
        f"Routines scored: {len(ran)} · **blind (0 killed): {len(blind)}** · partially blind: "
        f"{len(weak)} · all killed: {len(ran) - len(blind) - len(weak)}", "",
        "| ID | Routine | Killed / scored | Surviving mutations (line: orig → rep) |",
        "|---|---|---|---|",
    ]
    for r in sorted(ran, key=lambda r: (r["killed"] / r["scored"], r["id"])):
        surv = "<br>".join(f"L{m['line']}: `{m['orig']}`→`{m['rep']}` in `{m['code'][:70]}`"
                           for m in r["survivors"][:3])
        lines.append(f"| {r['id']} | `{r['name']}` | {r['killed']}/{r['scored']} | {surv} |")
    (args.out / "MUTATION_AUDIT.md").write_text("\n".join(lines) + "\n")
    print(f"scored={len(ran)} blind={len(blind)} weak={len(weak)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

#include "snes/snes.h"

/**
 * VehicleSpriteTbl is a data table rather than an executable routine.
 * It maps vehicle indices to sprite offsets and properties.
 * Each entry is 4 bytes: [X-offset, Y-offset, SpriteID, Flags/Attributes].
 */
static uint16_t get_vehicle_sprite_data(Snes *snes, int index, int offset_in_entry) {
    // The table is located at $BF:B4. 
    // In the target architecture, $BF is the ROM bank.
    // We access the ROM memory via the snes instance.
    // Index is multiplied by 4 because each entry is 4 bytes.
    uint32_t addr = 0xBFB4 + (index * 4) + offset_in_entry;
    
    // Since this is a table lookup, we simulate the read.
    // The harness provides access to ROM via the snes structure.
    // We assume the harness maps ROM into a reachable address space.
    return (uint16_t)snes->rom[addr]; 
}


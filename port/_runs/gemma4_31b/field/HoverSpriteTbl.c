#include "snes/snes.h"

// This routine is a data table mapping indices to sprite parameters.
// Since it is a .byte sequence (data) rather than executable code, 
// the C translation represents the table as a static array of bytes.
// The logic is a direct mapping: (Index * 4) -> 4 bytes of data.
static const uint8_t HOVER_SPRITE_TBL[] = {
    0x70, 0x6A, 0xC0, 0x2A,
    0x78, 0x6A, 0xC1, 0x2A,
    0x70, 0x72, 0xC2, 0x2A,
    0x78, 0x72, 0xC3, 0x2A,

    0x70, 0x6A, 0xC4, 0x2A,
    0x78, 0x6A, 0xC5, 0x2A,
    0x70, 0x72, 0xC6, 0x2A,
    0x78, 0x72, 0xC7, 0x2A,

    0x70, 0x6A, 0xC8, 0x2A,
    0x78, 0x6A, 0xC9, 0x2A,
    0x70, 0x72, 0xCA, 0x2A,
    0x78, 0x72, 0xCB, 0x2A,

    0x70, 0x6A, 0xCC, 0x2A,
    0x78, 0x6A, 0xCD, 0x2A,
    0x70, 0x72, 0xCE, 0x2A,
    0x78, 0x72, 0xCF, 0x2A,

    0x70, 0x6A, 0x2A, 0x2B,
    0x78, 0x6A, 0x2B, 0x2B,
    0x70, 0x72, 0x2C, 0x2B,
    0x78, 0x72, 0x2D, 0x2B
};

// Since this is a data table, the "translation" in the parity harness context 
// is usually implemented as a helper function to access the data.
uint8_t get_hover_sprite_byte(int offset) {
    return HOVER_SPRITE_TBL[offset];
}

